from typing import Tuple, Optional
from datetime import datetime, timezone


def format_watts(watts: Optional[float], prefer_kw_threshold: float = 1000.0) -> Tuple[str, str]:
    """
    Formats a wattage value with units.
    Returns (formatted_number, unit_label), e.g. ("1.75", "kW") or ("450", "W").
    """
    if watts is None:
        return ("--", "W")
    w = float(watts)
    if abs(w) >= prefer_kw_threshold:
        return (f"{w / 1000.0:.2f}", "kW")
    return (f"{int(round(w))}", "W")


def format_kwh(kwh: Optional[float]) -> Tuple[str, str]:
    """Formats cumulative energy in kWh. Returns (number_str, 'kWh')."""
    if kwh is None:
        return ("--", "kWh")
    val = float(kwh)
    if val < 0.01:
        return (f"{val * 1000.0:.1f}", "Wh")
    return (f"{val:.3f}", "kWh")


def format_temp(temp: Optional[float]) -> str:
    """Formats temperature in Celsius."""
    if temp is None:
        return "-- °C"
    return f"{float(temp):.1f} °C"


def format_humidity(hum: Optional[float]) -> str:
    """Formats relative humidity."""
    if hum is None:
        return "-- %"
    return f"{float(hum):.1f} %"


def format_lux(lux: Optional[int]) -> str:
    """Formats light level."""
    if lux is None:
        return "-- lux"
    return f"{int(lux)} lux"


def format_occupancy(occ: Optional[int]) -> str:
    """Formats occupancy as a human-readable state."""
    if occ is None:
        return "Unknown"
    return "Occupied" if int(occ) == 1 else "Vacant"


def format_delta_watts(delta: Optional[float]) -> Tuple[str, str]:
    """
    Formats delta in Watts.
    Returns (sign_formatted_val, direction_str ['up', 'down', 'flat']).
    """
    if delta is None:
        return ("0 W", "flat")
    d = float(delta)
    if abs(d) < 1.0:
        return ("0 W", "flat")
    sign = "+" if d > 0 else "-"
    abs_val = abs(d)
    direction = "up" if d > 0 else "down"
    if abs_val >= 1000.0:
        return (f"{sign}{abs_val / 1000.0:.2f} kW", direction)
    return (f"{sign}{int(round(abs_val))} W", direction)


def format_timestamp(iso_str: Optional[str]) -> str:
    """Formats an ISO-8601 UTC timestamp to HH:MM:SS format."""
    if not iso_str:
        return "--:--:--"
    try:
        dt = datetime.fromisoformat(iso_str.replace("Z", "+00:00"))
        # Local time display
        return dt.strftime("%H:%M:%S")
    except Exception:
        return iso_str[-8:] if len(iso_str) >= 8 else iso_str


