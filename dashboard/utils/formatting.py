def get_icon(name: str, size: int = 18, color: str = "currentColor") -> str:
    """Returns an inline SVG icon string."""
    template = ICONS.get(name, ICONS["info"])
    return template.format(size=size, color=color)


def render_html(html_str: str) -> None:
    """
    Safely renders HTML markup without Markdown turning indented lines into code blocks.
    Uses st.html when available (Streamlit >= 1.34), or textwrap.dedent as fallback.
    """
    import streamlit as st
    import textwrap
    clean_html = textwrap.dedent(html_str).strip()
    if hasattr(st, "html"):
        st.html(clean_html)
    else:
        st.markdown(clean_html, unsafe_allow_html=True)
